import boundaries from 'eslint-plugin-boundaries';

/**
 * Modular monolith boundaries — prepare domain modules for future microservice extraction.
 *
 * Layers (highest → lowest):
 *   application → infrastructure → domain modules → auth-public → permissions → shared
 *
 * Auth & permissions are fully isolated boundaries (future auth-service / permissions-service).
 * @see https://feature-sliced.design/docs/reference/layers/overview (layered import flow)
 */
const SHARED_TYPES = ['shared', 'env', 'autogenerated'];
const INFRASTRUCTURE = 'infrastructure';

/** Domain modules — each maps to a potential microservice. Auth is a separate isolated boundary. */
const DOMAIN_MODULES = [
	'users',
	'companies',
	'company-members',
	'specialists',
	'company-specialists',
	'services',
	'appointments',
	'notifications',
	'reviews',
	'dashboard',
	'health',
	'audit',
	'emails',
];

const domainType = (name) => `domain-${name}`;

const ALL_BOUNDARY_TYPES = [
	'auth',
	'auth-public',
	'permissions',
	...SHARED_TYPES,
	INFRASTRUCTURE,
	'application',
	...DOMAIN_MODULES.map(domainType),
];

const domainElements = DOMAIN_MODULES.map((name) => ({
	type: domainType(name),
	pattern: `src/modules/${name}`,
	partialMatch: false,
}));

const boundaryElements = [
	// Auth boundary (future auth microservice) — module + crypto/token helpers
	{ type: 'auth', pattern: 'src/modules/auth', partialMatch: false },
	{ type: 'auth', pattern: 'src/common/auth', partialMatch: false },

	// Auth public API — middleware other modules may use instead of auth internals
	{
		type: 'auth-public',
		pattern: 'src/common/middleware/requireAuth',
		partialMatch: false,
		exclusive: true,
	},
	{
		type: 'auth-public',
		pattern: 'src/common/middleware/optionalAuth',
		partialMatch: false,
		exclusive: true,
	},

	// Permissions boundary (future permissions / policy microservice)
	{ type: 'permissions', pattern: 'src/common/permissions', partialMatch: false },

	{ type: INFRASTRUCTURE, pattern: 'src/infrastructure', partialMatch: false },
	{ type: 'application', pattern: 'src/{app,main}', partialMatch: false },
	{ type: 'env', pattern: 'src/env', partialMatch: false },
	{ type: 'autogenerated', pattern: 'src/autogenerated', partialMatch: false },

	...domainElements,

	// Shared kernel — explicit segments (avoid broad src/common that shadows auth-public middleware)
	{ type: 'shared', pattern: 'src/common/errors', partialMatch: false },
	{ type: 'shared', pattern: 'src/common/schemas', partialMatch: false },
	{
		type: 'shared',
		pattern: 'src/common/middleware/{validate,errorHandler,notFoundHandler,requestLogger}',
		partialMatch: false,
	},
];

const domainModulePolicies = DOMAIN_MODULES.map((name) => ({
	from: { element: { type: domainType(name) } },
	allow: {
		to: {
			element: {
				types: [...SHARED_TYPES, INFRASTRUCTURE, 'auth-public', 'permissions', domainType(name)],
			},
		},
	},
}));

const AUTH_IMPORT_FORBIDDEN_FROM = [
	'shared',
	'permissions',
	'application',
	'env',
	'autogenerated',
	...DOMAIN_MODULES.map(domainType),
];

const boundaryPolicies = [
	// Same-folder / same-module imports
	{ allow: { dependency: { relationship: { to: 'internal' } } } },

	// Application wiring layer — composes all modules
	{
		from: { element: { type: 'application' } },
		allow: { to: { element: { types: ALL_BOUNDARY_TYPES } } },
	},

	// Infrastructure registers entities, migrations, event subscribers
	{
		from: { element: { type: INFRASTRUCTURE } },
		allow: { to: { element: { types: ALL_BOUNDARY_TYPES } } },
	},

	// Auth boundary — shared stack + users module (User entity coupling)
	{
		from: { element: { type: 'auth' } },
		allow: {
			to: {
				element: {
					types: ['auth', ...SHARED_TYPES, INFRASTRUCTURE, domainType('users')],
				},
			},
		},
	},

	// Auth public middleware — thin client of common/auth
	{
		from: { element: { type: 'auth-public' } },
		allow: { to: { element: { types: ['auth', ...SHARED_TYPES] } } },
	},

	// Permissions boundary — shared stack + company-members entity (membership lookup)
	{
		from: { element: { type: 'permissions' } },
		allow: {
			to: {
				element: {
					types: [...SHARED_TYPES, INFRASTRUCTURE, domainType('company-members')],
				},
			},
		},
	},

	// Permissions must not depend on auth internals
	{
		from: { element: { type: 'permissions' } },
		disallow: { to: { element: { types: ['auth', 'auth-public'] } } },
	},

	// Domain modules use auth via middleware + permissions API only
	...domainModulePolicies,

	// Shared kernel
	{
		from: { element: { type: 'shared' } },
		allow: { to: { element: { types: [...SHARED_TYPES, INFRASTRUCTURE] } } },
	},

	// Block auth internals outside auth boundary, auth-public, and infrastructure
	{
		from: { element: { types: AUTH_IMPORT_FORBIDDEN_FROM } },
		disallow: { to: { element: { type: 'auth' } } },
	},
];

export const microserviceBoundariesConfig = {
	plugins: {
		boundaries,
	},
	settings: {
		'import/resolver': {
			typescript: {
				project: './tsconfig.json',
				alwaysTryTypes: true,
			},
		},
		'boundaries/elements': boundaryElements,
		'boundaries/elements-single-match': false,
		'boundaries/include': ['src/**'],
	},
	rules: {
		...boundaries.configs.recommended.rules,
		'boundaries/dependencies': [
			'error',
			{
				default: 'disallow',
				message:
					'Microservice boundary violation: "{{from.element.types.[0]}}" cannot import "{{to.element.types.[0]}}" | Module isolation rules',
				policies: boundaryPolicies,
			},
		],
	},
};
