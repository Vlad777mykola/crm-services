import type { AppDashboardSummarySchema, CompanyDashboardSummarySchema } from '@/autogenerated/types/index.js';
import { AppError } from '@/common/errors/AppError.js';
import { requireCompanyRole } from '@/common/permissions/companyPermissions.js';
import { AppDataSource } from '@/infrastructure/database/data-source.js';
import { Appointment, AppointmentStatus } from '@/modules/appointments/appointment.entity.js';
import { CompanyMember, CompanyMemberRole, CompanyMemberStatus } from '@/modules/company-members/company-member.entity.js';
import {
  CompanySpecialistRequest,
  CompanySpecialistRequestStatus,
} from '@/modules/company-specialists/company-specialist-request.entity.js';
import { CompanySpecialist, CompanySpecialistStatus } from '@/modules/company-specialists/company-specialist.entity.js';
import { Company } from '@/modules/companies/company.entity.js';
