/**
 * Generates docker/verify/traefik/dynamic.yml from docker/dev/traefik/dynamic.host.yml
 * by remapping host.docker.internal ports to verify namespace (+10000).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { allDevAppPorts, verifyAppPort } from '../dev/port-registry.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = path.join(ROOT, 'docker/dev/traefik/dynamic.host.yml');
const TARGET = path.join(ROOT, 'docker/verify/traefik/dynamic.yml');

let content = fs.readFileSync(SOURCE, 'utf8');

for (const devPort of allDevAppPorts()) {
  const verifyPort = verifyAppPort(devPort);
  content = content.replaceAll(`host.docker.internal:${devPort}`, `host.docker.internal:${verifyPort}`);
}

const header = `# Generated by scripts/verify/generate-verify-traefik.mjs — do not edit by hand.\n`;
fs.writeFileSync(TARGET, header + content);
console.log(`[generate-verify-traefik] wrote ${TARGET}`);
