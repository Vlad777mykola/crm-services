/**
 * Generates docker/test/traefik/dynamic.yml from dev routes with test app ports (+20000).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { allDevAppPorts, testAppPort } from '../dev/port-registry.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = path.join(ROOT, 'docker/dev/traefik/dynamic.host.yml');
const TARGET = path.join(ROOT, 'docker/test/traefik/dynamic.yml');

let content = fs.readFileSync(SOURCE, 'utf8');

for (const devPort of allDevAppPorts()) {
  const testPort = testAppPort(devPort);
  content = content.replaceAll(`host.docker.internal:${devPort}`, `host.docker.internal:${testPort}`);
}

const header = '# Generated by scripts/test/generate-test-traefik.mjs — test ports (+20000)\n';
fs.writeFileSync(TARGET, header + content);
console.log(`[generate-test-traefik] wrote ${TARGET}`);
